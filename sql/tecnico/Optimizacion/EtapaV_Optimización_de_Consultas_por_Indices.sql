ALTER TABLE PROVEEDOR ADD CONSTRAINT PK_PROVEEDOR PRIMARY KEY (id_proveedor), CONSTRAINT UQ_PROVEEDOR_CUIL UNIQUE (cuil), CONSTRAINT CK_PROVEEDOR_CUIL CHECK (cuil LIKE '[0-9][0-9]-[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]-[0-9]'), CONSTRAINT CK_PROVEEDOR_EMAIL CHECK (email LIKE '%_@_%.__%');

CREATE TABLE PRODUCTO (
  id_producto INT NOT NULL IDENTITY (1,1),
  nombre VARCHAR(100) NOT NULL,
  precio DECIMAL(10,2) NOT NULL,
  stock INT NOT NULL,
  id_categoria INT NOT NULL,
  id_proveedor INT NOT NULL
);
ALTER TABLE PRODUCTO ADD CONSTRAINT PK_PRODUCTO PRIMARY KEY (id_producto), CONSTRAINT DF_PRODUCTO_STOCK DEFAULT 0 FOR stock, CONSTRAINT CK_PRODUCTO_PRECIO CHECK (precio > 0), CONSTRAINT CK_PRODUCTO_STOCK CHECK (stock >= 0), CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (id_categoria) REFERENCES CATEGORIA(id_categoria) ON DELETE NO ACTION ON UPDATE CASCADE, CONSTRAINT FK_PRODUCTO_PROVEEDOR FOREIGN KEY (id_proveedor) REFERENCES PROVEEDOR(id_proveedor) ON DELETE NO ACTION ON UPDATE CASCADE;

CREATE TABLE CLIENTE (
  id_cliente INT NOT NULL IDENTITY (1,1),
  nombre VARCHAR(50) NOT NULL,
  apellido VARCHAR(50) NOT NULL,
  dni VARCHAR(8) NOT NULL,
  email VARCHAR(100) NOT NULL,
  telefono VARCHAR(20) NOT NULL
