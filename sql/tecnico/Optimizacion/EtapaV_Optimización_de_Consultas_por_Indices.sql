ALTER TABLE CLIENTE ADD CONSTRAINT PK_CLIENTE PRIMARY KEY (id_cliente), CONSTRAINT UQ_CLIENTE_DNI UNIQUE (dni), CONSTRAINT CK_CLIENTE_DNI CHECK (dni LIKE '[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]'), CONSTRAINT CK_CLIENTE_EMAIL CHECK (email LIKE '%_@_%.__%');

CREATE TABLE EMPLEADO (
  id_empleado INT NOT NULL IDENTITY (1,1),
  nombre VARCHAR(50) NOT NULL,
  apellido VARCHAR(50) NOT NULL,
  legajo VARCHAR(10) NOT NULL,
  telefono VARCHAR(20) NOT NULL
);
ALTER TABLE EMPLEADO ADD CONSTRAINT PK_EMPLEADO PRIMARY KEY (id_empleado), CONSTRAINT UQ_EMPLEADO_LEGAJO UNIQUE (legajo);

CREATE TABLE FORMA_PAGO (
  id_forma_pago INT NOT NULL IDENTITY (1,1),
  descripcion VARCHAR(50) NOT NULL
);
ALTER TABLE FORMA_PAGO ADD CONSTRAINT PK_FORMA_PAGO PRIMARY KEY (id_forma_pago), CONSTRAINT UQ_FORMA_PAGO_DESCRIPCION UNIQUE (descripcion);

CREATE TABLE VENTA (
  id_venta INT NOT NULL IDENTITY (1,1),
  fecha DATETIME NOT NULL,
  total DECIMAL(12,2) NOT NULL,
  id_cliente INT NOT NULL,
  id_empleado INT NOT NULL,
  id_forma_pago INT NOT NULL
);
ALTER TABLE VENTA ADD CONSTRAINT PK_VENTA PRIMARY KEY (id_venta), CONSTRAINT DF_VENTA_FECHA DEFAULT GETDATE() FOR fecha, CONSTRAINT CK_VENTA_TOTAL CHECK (total >= 0), CONSTRAINT FK_VENTA_CLIENTE FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id_cliente) ON DELETE NO ACTION ON UPDATE CASCADE, CONSTRAINT FK_VENTA_EMPLEADO FOREIGN KEY (id_empleado) REFERENCES EMPLEADO(id_empleado) ON DELETE NO ACTION ON UPDATE CASCADE, CONSTRAINT FK_VENTA_FORMA_PAGO FOREIGN KEY (id_forma_pago) REFERENCES FORMA_PAGO(id_forma_pago) ON DELETE NO ACTION ON UPDATE CASCADE;

CREATE TABLE DETALLE_VENTA (
  id_detalle INT NOT NULL IDENTITY (1,1),
