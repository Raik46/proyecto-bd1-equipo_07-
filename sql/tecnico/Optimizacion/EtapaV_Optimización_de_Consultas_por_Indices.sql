SET NOCOUNT ON;

-- Utilizamos un CTE en cascada (Tally Table) para generar 1 millón de filas rápidamente
WITH
  L0   AS (SELECT 1 AS c UNION ALL SELECT 1),               
  L1   AS (SELECT 1 AS c FROM L0 A CROSS JOIN L0 B),        
  L2   AS (SELECT 1 AS c FROM L1 A CROSS JOIN L1 B),        
  L3   AS (SELECT 1 AS c FROM L2 A CROSS JOIN L2 B),        
  L4   AS (SELECT 1 AS c FROM L3 A CROSS JOIN L3 B),        
  L5   AS (SELECT 1 AS c FROM L4 A CROSS JOIN L4 B),        
  Nums AS (SELECT ROW_NUMBER() OVER(ORDER BY (SELECT NULL)) AS n FROM L5)
INSERT INTO VENTA (fecha, total, id_cliente, id_empleado, id_forma_pago)
SELECT TOP (1000000)
    DATEADD(minute, n, '2020-01-01'), -- Fechas incrementales espaciadas por minutos
    CAST(RAND(CHECKSUM(NEWID())) * 1000 AS DECIMAL(12,2)),
    1, 1, 1
FROM Nums;
GO
SET NOCOUNT OFF;
PRINT 'Carga masiva finalizada.';
